# Reserved words in Python
# Full list of Python reserved words:
# False, None, True, and, as, assert, async, await,
# break, class, continue, def, del, elif, else, except,
# finally, for, from, global, if, import, in, is, lambda,
# nonlocal, not, or, pass, raise, return, try, while, with, yield


# 5 reserved word definitions:

# def — used to define (declare) a ^^function^^, a reusable block of code.
# Example: def greet(): print("Hello!")

# if — starts a ^^conditional statement^^; runs a block of code only when a condition is True.
# Example: if age >= 18: print("Adult")

# return — exits a function and sends a value back to the code that called it.
# Example: def add(a, b): return a + b

# import — loads an external ^^module^^ (a library of pre-written code) into your script.
# Example: import math

# for — creates a ^^loop^^ that iterates over items in a ^^sequence^^ (like a list or range).
# Example: for i in range(5): print(i)

